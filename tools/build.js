#!/usr/bin/env node
"use strict";
// Deterministic dependency-free CommonJS bundle for a single Shadowrocket script.
const fs=require("node:fs");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const order=["src/config.js","src/request.js","src/sse.js","src/deepseek.js","src/core.js","src/entry.js"];
const header='/* AUTO-GENERATED by tools/build.js. DO NOT EDIT.\n * AIES v0.2.1-lab | Original SAIR protocol research (c) 2026 boitar, MIT.\n * EXPERIMENTAL / NOT REAL-DEVICE VERIFIED. REJECT guard required.\n */\n(function(){\n"use strict";\nvar factories={\n';
const tail='\n};\nvar cache={};\nfunction load(id){\n  if (cache[id]) return cache[id].exports;\n  if (!Object.prototype.hasOwnProperty.call(factories,id)) throw new Error("Module missing");\n  var mod={exports:{}};cache[id]=mod;\n  function req(relative){\n    if (typeof relative!=="string" || relative.indexOf("./")!==0 || relative.indexOf("..")!==-1) throw new Error("Invalid import");\n    var target=id.slice(0,id.lastIndexOf("/")+1)+relative.slice(2)+".js";\n    return load(target);\n  }\n  factories[id](mod,mod.exports,req);return mod.exports;\n}\nload("src/entry.js");\n})();\n';
function normalize(s){return s.replace(/\r\n/g,"\n").trimEnd()+"\n";}
const payload=header+order.map(id=>"  "+JSON.stringify(id)+":function(module,exports,require){\n"+
  normalize(fs.readFileSync(path.join(root,id),"utf8"))+"  }").join(",\n")+tail;
const output=path.join(root,"scripts/sairs_router.js");
if(process.argv.includes("--check")){
  if(!fs.existsSync(output)||fs.readFileSync(output,"utf8")!==payload){
    console.error("Bundle drift: run node tools/build.js and commit generated script.");
    process.exit(1);
  }
  console.log("Generated Shadowrocket bundle matches source.");
} else {
  fs.mkdirSync(path.dirname(output),{recursive:true});
  fs.writeFileSync(output,payload);
  console.log("Wrote scripts/sairs_router.js ("+payload.length+" chars)");
}
